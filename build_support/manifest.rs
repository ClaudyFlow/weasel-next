//! Application-manifest embedding for both Windows toolchains.
//!
//! MSVC's linker accepts a manifest directly (`/MANIFEST:EMBED` plus
//! `/MANIFESTINPUT:<file>`). GNU targets have no equivalent switch, so the
//! manifest is compiled into an `RT_MANIFEST` resource instead -- which is the
//! same thing `/MANIFEST:EMBED` puts into the image.

use std::path::{Path, PathBuf};
#[path = "toolchain.rs"]
mod toolchain;

/// Embeds `manifest` into the `binary` target (an example: `Weasel-Next-Server`).
///
/// `disable_msvc_default_uac` suppresses the MSVC linker's default UAC fragment
/// (`/MANIFESTUAC:NO`) for manifests that own `requestedExecutionLevel`
/// themselves. A GNU-linked image has no default fragment to suppress, so the
/// flag is MSVC-only and ignored elsewhere.
pub fn embed(binary: &str, manifest: &Path, disable_msvc_default_uac: bool) {
    println!("cargo:rerun-if-changed={}", manifest.display());

    if toolchain::is_msvc_target() {
        println!("cargo:rustc-link-arg-bin={binary}=/MANIFEST:EMBED");
        if disable_msvc_default_uac {
            println!("cargo:rustc-link-arg-bin={binary}=/MANIFESTUAC:NO");
        }
        println!(
            "cargo:rustc-link-arg-bin={binary}=/MANIFESTINPUT:{}",
            manifest.display()
        );
        return;
    }

    // `RT_MANIFEST` is resource type 24 for a `1 24 "<file>"` entry.
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR is not set"));
    let resource = out.join(format!("{binary}-manifest.rc"));
    let manifest = manifest
        .to_str()
        .expect("manifest path must be UTF-8")
        .replace('\\', "/");
    std::fs::write(
        &resource,
        format!("// Generated by build_support/manifest.rs.\n1 24 \"{manifest}\"\n"),
    )
    .expect("failed to write manifest resource script");
    println!("cargo:rerun-if-changed={}", resource.display());

    embed_resource::compile_for(&resource, [binary], embed_resource::NONE)
        .manifest_required()
        .expect("failed to embed application manifest");
}
